    // Método para cargar canciones disponibles (todas las canciones)
    private void cargarCancionesDisponibles() {
        CancionDAO cancionDao = new CancionDAO();
        List<Cancion> canciones = cancionDao.listarTodas();
        System.out.println("cancionesDisponibles: " + cancionesDisponibles);
        if (cancionesDisponibles == null) {
            cancionesDisponibles = new ArrayList<>();  // Evita null
        }

        cancionesDisponibles = canciones;  // <-- Agrega esta línea
        DefaultListModel<String> modelo = new DefaultListModel<>();
        for (Cancion cancion : canciones) {
            // Mostrar nombre, autor y duración
            modelo.addElement(cancion.getNombre() + " - " + cancion.getAutorNombre() + " - " + cancion.getDuracion());
        }
        jLista.setModel(modelo);
    }

    // Método para cargar canciones en la lista actual
    private void cargarCancionesEnLista() {
        Canciones_listasDAO cancionesDao = new Canciones_listasDAO();
        List<Canciones_listas> cancionesEnLista = cancionesDao.listarCancionesPorLista(idLista);
        cancionesEnListaActual = cancionesEnLista;
        DefaultListModel<String> modelo = new DefaultListModel<>();
        CancionDAO cancionDao = new CancionDAO();
        for (Canciones_listas item : cancionesEnLista) {
            Cancion cancion = cancionDao.obtenerPorId(item.getId_cancion());
            if (cancion != null) {
                // Mostrar nombre, autor y duración
                modelo.addElement(cancion.getNombre() + " - " + cancion.getAutorNombre() + " - " + cancion.getDuracion());
            } else {
                modelo.addElement("Canción no encontrada (ID: " + item.getId_cancion() + ")");
            }
        }
        jListaComprador.setModel(modelo);
    }

