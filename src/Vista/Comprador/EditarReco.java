    private void btnAgregarCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarCancionActionPerformed

        int selectedIndex = jLista.getSelectedIndex();
        if (selectedIndex != -1) {
            Cancion cancionSeleccionada = cancionesDisponibles.get(selectedIndex);

            // Recargar la lista actual desde la BD para asegurar datos frescos
            cargarCancionesEnLista();

            // Validación: Contar cuántas veces ya está la canción en la lista actual
            long count = cancionesEnListaActual.stream()
                    .filter(item -> item.getId_cancion() == cancionSeleccionada.getId_cancion())
                    .count();

            if (count >= 2) {
                JOptionPane.showMessageDialog(this, "No se puede agregar la misma canción más de dos veces a la recopilación.");
                return;  // No proceder con la inserción
            }

            // Proceder con la inserción si la validación pasa
            Canciones_listas nueva = new Canciones_listas();
            nueva.setId_lista(idLista);
            nueva.setId_cancion(cancionSeleccionada.getId_cancion());
            Canciones_listasDAO dao = new Canciones_listasDAO();
            if (dao.insertarCancionLista(nueva)) {
                JOptionPane.showMessageDialog(this, "Canción agregada exitosamente.");
                cargarCancionesEnLista(); // Recargar la lista de la recopilación
            } else {
                JOptionPane.showMessageDialog(this, "Error al agregar la canción.");
            }
        }
    }//GEN-LAST:event_btnAgregarCancionActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        Lista_reproduccionDAO dao = new Lista_reproduccionDAO();
        // Obtener los valores actuales de la lista desde la BD
        Lista_reproduccion listaActual = dao.buscarPorIdLista(idLista);
        if (listaActual == null) {
            JOptionPane.showMessageDialog(this, "Error: No se pudo obtener la lista actual.");
            return;
        }
        // Obtener los nuevos valores desde la UI
        String nuevoNombre = txtNombre.getText().trim();
        String nuevaPublica = rdbPublica.isSelected() ? "Sí" : "No";
        // Comparar con los valores actuales
        boolean nombreCambio = !nuevoNombre.equals(listaActual.getNombre());
        boolean publicaCambio = !nuevaPublica.equals(listaActual.getPublica());
        if (!nombreCambio && !publicaCambio) {
            JOptionPane.showMessageDialog(this, "No se han realizado cambios en la recopilación.");
            return;
        }
        // Hay cambios: proceder con la modificación
        Lista_reproduccion lista = new Lista_reproduccion();
        lista.setId_lista(idLista);
        lista.setNombre(nuevoNombre);
        lista.setPublica(nuevaPublica);
        if (dao.modificarListaReproduccion(lista)) {
            JOptionPane.showMessageDialog(this, "Cambios guardados exitosamente.");

            // Refrescar la lista en la ventana padre (Comprador)
            if (padre != null) {
                padre.cargarListasReproduccion();
            }

            // Cerrar la ventana para que los cambios sean visibles
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar cambios.");
        }


    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int selectedIndex = jListaComprador.getSelectedIndex();
        if (selectedIndex != -1) {
            Canciones_listas cancionListaSeleccionada = cancionesEnListaActual.get(selectedIndex);
            Canciones_listasDAO dao = new Canciones_listasDAO();
            if (dao.eliminarCancionLista(cancionListaSeleccionada.getId_cancion_lista())) {
                JOptionPane.showMessageDialog(this, "Canción eliminada exitosamente.");
                cargarCancionesEnLista(); // Recargar la lista de la recopilación
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar la canción.");
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

